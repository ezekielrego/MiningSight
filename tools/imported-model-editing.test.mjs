import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const temp = await mkdtemp(path.join(tmpdir(), 'miningsight-model-edits-'));
try {
  await build({ stdin: { contents: `export * from './src/scene/modelEditing'; export * from './src/scene/importedModel'; export * as THREE from 'three';`, resolveDir: process.cwd(), loader: 'ts' }, outfile: path.join(temp, 'model.mjs'), bundle: true, platform: 'node', format: 'esm' });
  const { THREE, ImportedModelController, validateModelEditProposal, applyModelEdits, flattenObjects, editableModelContext } = await import(pathToFileURL(path.join(temp, 'model.mjs')));
  const root = new THREE.Group(), group = new THREE.Group();
  const mesh = new THREE.Mesh(new THREE.BoxGeometry(2, 2, 2), new THREE.MeshStandardMaterial({ color: 0x445566 }));
  mesh.name = 'Panel'; group.add(mesh); root.add(group);
  const controller = new ImportedModelController(root, { id: 'asset_test', name: 'Test.glb' });
  const initial = [structuredClone(controller.tree)], id = 'imported:asset_test/0/0';
  assert.equal(flattenObjects(initial).length, 3);
  assert.equal(controller.nodes.get(id), mesh);
  assert.equal(editableModelContext(initial, 'asset_test').parts[2].parentId, 'imported:asset_test/0');
  const proposal = operations => ({ version: 1, assetId: 'asset_test', guidance: 'Test explicit edits', operations });
  const transform = validateModelEditProposal(proposal([{ type: 'transform', targetId: id, position: { x: 100, y: 200, z: 0 }, rotation: { x: 0, y: 90, z: 0 } }]), initial, 'asset_test');
  const changed = applyModelEdits(initial, transform.operations);
  controller.applyScene(changed);
  assert.equal(mesh.position.x, 1); assert.equal(mesh.position.y, 2); assert.equal(mesh.rotation.y, Math.PI / 2);
  assert.equal(flattenObjects(initial)[2].position.x, 0, 'history remains immutable');
  controller.applyScene(initial);
  const ray = new THREE.Raycaster(new THREE.Vector3(0, 0, 5), new THREE.Vector3(0, 0, -1));
  assert.ok(controller.intersections(ray).length);
  controller.setDisplayMode('points');
  assert.equal(mesh.material.visible, false); assert.ok(mesh.children.some(node => node.isPoints && node.visible));
  assert.ok(controller.intersections(ray).length, 'point view still supports surface picking');
  controller.setDisplayMode('wireframe');
  assert.equal(mesh.material.wireframe, true); assert.equal(mesh.material.visible, true);
  controller.setDisplayMode('gouraud_lines');
  assert.equal(mesh.material.wireframe, false); assert.ok(mesh.children.some(node => node.isLineSegments && node.visible));
  controller.setDisplayMode('gouraud'); controller.setSelection(id); controller.setSelection(null);
  assert.equal(mesh.material.color.getHex(), 0x445566);
  const hidden = applyModelEdits(initial, [{ type: 'hide', targetId: id }]); controller.applyScene(hidden);
  assert.equal(controller.intersections(ray).length, 0);
  const removed = applyModelEdits(initial, [{ type: 'remove', targetId: id }]); controller.applyScene(removed);
  assert.equal(mesh.visible, false); assert.equal(flattenObjects(removed).length, 2);
  assert.ok(mesh.geometry.getAttribute('position'), 'remove preserves geometry for undo');
  controller.applyScene(initial); assert.equal(mesh.visible, true); assert.ok(controller.intersections(ray).length);
  controller.applyScene(applyModelEdits(initial, [{ type: 'remove', targetId: initial[0].id }])); assert.equal(root.visible, false);
  controller.applyScene(initial); assert.equal(root.visible, true);
  assert.throws(() => validateModelEditProposal(proposal([{ type: 'hide', targetId: 'imported:other/0' }]), initial, 'asset_test'));
  assert.throws(() => validateModelEditProposal({ ...proposal([{ type: 'hide', targetId: id }]), assetId: 'other' }, initial, 'asset_test'));
  assert.throws(() => validateModelEditProposal(proposal([{ type: 'transform', targetId: id, position: { x: NaN, y: 0, z: 0 } }]), initial, 'asset_test'));
  assert.throws(() => validateModelEditProposal(proposal([{ type: 'transform', targetId: id, scale: { x: 0, y: 1, z: 1 } }]), initial, 'asset_test'));
  assert.throws(() => validateModelEditProposal(proposal([{ type: 'execute', targetId: id }]), initial, 'asset_test'));
  assert.throws(() => validateModelEditProposal(proposal([{ type: 'remove', targetId: 'imported:asset_test/0' }, { type: 'hide', targetId: id }]), initial, 'asset_test'));
  const locked = structuredClone(initial); locked[0].locked = true;
  assert.throws(() => validateModelEditProposal(proposal([{ type: 'hide', targetId: id }]), locked, 'asset_test'));
  assert.equal(editableModelContext(locked, 'asset_test').parts[2].locked, true);
  controller.dispose();
  console.log('PASS: stable nested part IDs; display modes; selection restoration; transforms; hide/remove/undo; hidden picking; scoped guided edits; locked ancestors; malformed proposals.');
} finally { await rm(temp, { recursive: true, force: true }); }
