/**
 * Creates the appropriate Three.js MiningTunnelRig based on the requested preset ID
 * and any optional custom parameters.
 */
export function createTunnelRigByPreset(
  presetId: TunnelPresetId,
  customParams?: Partial<ProceduralTunnelParams>
): MiningTunnelRig {
  if (presetId === 'branching_drift') return createBranchingDrift(customParams);
  if (presetId === 'classic_diorama') {
    return createMiningTunnel();
  }
  
  if (presetId === 'rugged_timbered_photo') {
    return createRuggedTimberedTunnel(customParams);
  }

  // ai_custom
  const mergedParams = {
    ...TUNNEL_PRESETS.ai_custom.defaultParams,
    ...customParams,
  };
  return createRuggedTimberedTunnel(mergedParams);
}

